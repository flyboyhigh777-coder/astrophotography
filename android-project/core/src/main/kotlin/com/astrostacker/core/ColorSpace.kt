package com.astrostacker.core

/**
 * Преобразование sRGB (гамма-кодированные значения, как хранятся в обычных
 * JPEG/HEIF/PNG и как их отдаёт `BitmapFactory`) ↔ линейный свет. Стандартная
 * формула sRGB EOTF/OETF (IEC 61966-2-1, та же, что использует PixInsight и
 * большинство астро-ПО при импорте/экспорте).
 *
 * Это не декоративная деталь: весь пайплайн (`StackCombiner` — усреднение
 * значений одного пикселя по кадрам, `BackgroundExtractor`/`autoMidtoneForBackground`
 * — подбор уровня растяжки по яркости фона) статистически корректен только для
 * ЛИНЕЙНЫХ значений яркости (см. комментарий к [FloatImage]: "линейные, после
 * декодирования гаммы"). Гамма-кодирование — нелинейная функция; если усреднять
 * или клиппировать по κ-σ гамма-кодированные значения "как есть", результат
 * статистически смещён (тени и света взвешиваются неправильно), а подбор
 * средней точки растяжки по формуле MTF (рассчитанной для линейных данных)
 * даёт видимо неверную, обычно пересвеченную картинку. Поэтому декодирование
 * изображения в [FloatImage] обязано проходить через [srgbToLinear] (см.
 * `:app` `ImageDecoding.kt`), а обратное превращение в `Bitmap` для показа на
 * экране или сохранения — через [linearToSrgb] (см. `:app`
 * `ProcessingViewModel.kt`/`ExportRepository.kt`).
 */
object ColorSpace {

    private const val LUT_SIZE = 256

    /**
     * Таблица sRGB(0..255) → линейное(0..1) для быстрого поэлементного
     * декодирования 8-битных каналов `Bitmap.ARGB_8888` — без таблицы пришлось
     * бы на каждый пиксель каждого входного кадра трижды вызывать `pow`
     * (десятки миллионов вызовов на серию из 15-20 кадров по 3000+ px стороне).
     */
    private val decodeLut = FloatArray(LUT_SIZE) { i -> srgbToLinear(i / (LUT_SIZE - 1).toFloat()) }

    /** Точная формула (IEC 61966-2-1) для произвольного значения 0..1; используется для построения [decodeLut]. */
    fun srgbToLinear(c: Float): Float {
        val x = c.coerceIn(0f, 1f)
        return if (x <= 0.04045f) x / 12.92f
        else Math.pow(((x + 0.055) / 1.055).toDouble(), 2.4).toFloat()
    }

    /** Обратное преобразование: линейное 0..1 → sRGB (гамма-кодированное) 0..1. */
    fun linearToSrgb(c: Float): Float {
        val x = c.coerceIn(0f, 1f)
        return if (x <= 0.0031308f) x * 12.92f
        else (1.055 * Math.pow(x.toDouble(), 1.0 / 2.4) - 0.055).toFloat()
    }

    /** Быстрый путь по таблице [decodeLut] для 8-битного канала (0..255) — обычный случай при декодировании `Bitmap`. */
    fun srgbByteToLinear(byteValue: Int): Float = decodeLut[byteValue.coerceIn(0, LUT_SIZE - 1)]
}
